function generateCandles(
  basePrice: number,
  count: number,
  trend: number,
  volatility: number,
  whaleEntries: Record<number, string> = {}
): Candle[] {
  const now = Date.now();
  const candles: Candle[] = [];
  let price = basePrice;
  for (let i = count - 1; i >= 0; i--) {
    const seed = Math.sin(i * 1.7 + basePrice * 1000) * 0.5 + Math.cos(i * 0.9) * 0.5;
    const delta = (trend + seed * volatility) * price;
    const open = price;
    const close = Math.max(basePrice * 0.25, open + delta);
    const high = Math.max(open, close) * (1 + Math.abs(seed) * volatility * 0.6);
    const low = Math.min(open, close) * (1 - Math.abs(seed) * volatility * 0.5);
    const idx = count - 1 - i;
    candles.push({
      ts: now - i * 60_000,
      open,
      high,
      low,
      close,
      volume: Math.round(1200 + Math.abs(seed) * 4800),
      whaleEntry: whaleEntries[idx],
    });
    price = close;
  }
  return candles;
}

